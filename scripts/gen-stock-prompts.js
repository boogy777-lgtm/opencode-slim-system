// Maintainer-only refresh of the fail-closed stock prompt allowlist. Never run at plugin startup.
import { createHash } from "node:crypto"
import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const ref = "9bbb8ce18c80f099e0e448775f59d965ead40a21" // OpenCode v2.2.5
const base = `https://raw.githubusercontent.com/anomalyco/opencode/${ref}`
const sources = {
  core: "packages/core/src/session/runner/prompt/system.txt",
  gpt: "packages/core/src/plugin/system-prompt/gpt.txt",
  astra: "packages/core/src/plugin/system-prompt/gpt-astra.txt",
  kimi: "packages/core/src/plugin/system-prompt/kimi.txt",
  trinity: "packages/core/src/plugin/system-prompt/trinity.txt",
  anthropic: "packages/core/src/plugin/system-prompt/anthropic.txt",
}

const fixtures = path.join(root, "tests", "fixtures", "stock")
await mkdir(fixtures, { recursive: true })
const entries = await Promise.all(Object.entries(sources).map(async ([name, source]) => {
  const response = await fetch(`${base}/${source}`)
  if (!response.ok) throw new Error(`Cannot load ${source}: ${response.status}`)
  const text = await response.text()
  await writeFile(path.join(fixtures, `${name}.txt`), text)
  return [name, text]
}))
const templates = Object.fromEntries(entries)
const license = await fetch(`${base}/LICENSE`)
if (!license.ok) throw new Error(`Cannot load OpenCode license: ${license.status}`)
await writeFile(path.join(fixtures, "LICENSE"), await license.text())

const guidance = [
  [
    "- Prefer dedicated tools over shell commands; fall back to the shell when a tool cannot do what you need.",
    '- Do not chain shell commands with separators like `echo "====";` or `printf \'---\'`; the output becomes noisy in a way that makes the user\'s side of the conversation worse.',
  ].join("\n"),
  "- Use the write tool to create files or completely replace their content. Prefer using the edit tool for targeted changes.",
  '- Use the edit tool for targeted changes to existing text files. It replaces the exact text in `oldString` with `newString`, and the values must differ. By default, `oldString` must occur exactly once. If it occurs multiple times, include more surrounding context to make it unique or set `replaceAll` to true to replace every occurrence.',
]
const hashes = new Set()
for (let mask = 0; mask < 8; mask++) {
  const renderedGuidance = guidance.filter((_, bit) => mask & (1 << bit)).join("\n")
  const render = (text) => text.replace("${OPENCODE_TOOL_GUIDANCE}", renderedGuidance)
  const variants = [
    ...Object.entries(templates).filter(([name]) => name !== "anthropic").map(([, text]) => render(text)),
    `${render(templates.core)}\n\n${render(templates.anthropic)}`,
  ]
  for (const text of variants) hashes.add(createHash("sha256").update(text).digest("hex"))
}
await writeFile(path.join(root, "src", "stock-prompts.js"), [
  "// Generated by scripts/gen-stock-prompts.js from MIT-licensed OpenCode v2.2.5.",
  `// Source commit: ${ref}. No network access is used by the plugin.`,
  "export const STOCK_PROMPT_HASHES = new Set([",
  ...[...hashes].sort().map((hash) => `  "${hash}",`),
  "])",
  "",
].join("\n"))
console.log(`Generated ${hashes.size} exact stock prompt hashes`)
